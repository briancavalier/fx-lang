use crate::ir::*;

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct JavaScriptModule {
    pub module: String,
    pub path: String,
    pub source: String,
}

pub fn emit_javascript_modules(program: &CoreProgram) -> Vec<JavaScriptModule> {
    program
        .modules
        .iter()
        .map(|module| JavaScriptModule {
            module: module.name.clone(),
            path: module_path(&module.name),
            source: emit_module(module),
        })
        .collect()
}

pub fn module_path(module: &str) -> String {
    format!("{}.mjs", module.replace('.', "/"))
}

pub fn local_identifier(name: &CoreLocalName) -> String {
    user_identifier(&name.0)
}

pub fn global_identifier(name: &CoreGlobalName) -> String {
    user_identifier(&name.name)
}

fn emit_module(module: &CoreModule) -> String {
    let mut source = String::new();
    source.push_str("// Generated by fx Phase 2.5 JavaScript emitter.\n");
    source.push_str(&format!("// module {}\n", module.name));

    for import in &module.imports {
        source.push_str(&format!(
            "import * as {} from \"{}\";\n",
            import_namespace(&import.module),
            relative_import_path(&module.name, &import.module)
        ));
    }

    if !module.imports.is_empty() {
        source.push('\n');
    }

    for declaration in &module.declarations {
        match declaration {
            CoreDecl::Type(declaration) => emit_type_decl(&mut source, declaration),
            CoreDecl::Value(declaration) => emit_value_decl(&mut source, declaration),
        }
    }

    source
}

fn emit_type_decl(source: &mut String, declaration: &CoreTypeDecl) {
    let shape = match &declaration.shape {
        CoreTypeShape::Record { fields } => {
            format!(
                "record({})",
                fields
                    .iter()
                    .map(|field| field.name.as_str())
                    .collect::<Vec<_>>()
                    .join(",")
            )
        }
        CoreTypeShape::Variant { cases } => {
            format!(
                "variant({})",
                cases
                    .iter()
                    .map(|case| case.name.as_str())
                    .collect::<Vec<_>>()
                    .join(",")
            )
        }
    };
    source.push_str(&format!(
        "// type {} {}\n",
        display_global(&declaration.name),
        shape
    ));
}

fn emit_value_decl(source: &mut String, declaration: &CoreValueDecl) {
    let name = global_identifier(&declaration.name);
    if declaration.export {
        source.push_str("export ");
    }
    source.push_str(&format!(
        "function {name}() {{ throw new Error(\"fx codegen for {} is not implemented yet\"); }}\n",
        display_global(&declaration.name)
    ));
}

fn user_identifier(name: &str) -> String {
    let mut output = String::from("__fx_user_");
    for (index, ch) in name.chars().enumerate() {
        if (index == 0 && is_ident_start(ch)) || (index > 0 && is_ident_continue(ch)) {
            output.push(ch);
        } else {
            output.push('_');
            output.push_str(&(ch as u32).to_string());
            output.push('_');
        }
    }
    output
}

fn import_namespace(module: &str) -> String {
    let mut output = String::from("__fx_import_");
    for ch in module.chars() {
        if is_ident_continue(ch) {
            output.push(ch);
        } else {
            output.push('_');
        }
    }
    output
}

fn relative_import_path(from: &str, to: &str) -> String {
    let from_depth = from.split('.').count().saturating_sub(1);
    let mut path = String::new();
    for _ in 0..from_depth {
        path.push_str("../");
    }
    path.push_str(&module_path(to));
    if !path.starts_with('.') {
        path.insert_str(0, "./");
    }
    path
}

fn is_ident_start(ch: char) -> bool {
    ch == '_' || ch == '$' || ch.is_ascii_alphabetic()
}

fn is_ident_continue(ch: char) -> bool {
    is_ident_start(ch) || ch.is_ascii_digit()
}

fn display_global(name: &CoreGlobalName) -> String {
    format!("{}.{}", name.module, name.name)
}

#[cfg(test)]
mod tests {
    use super::*;
    use fx_core::Type;
    use fx_syntax::span::Span;
    use std::fs;
    use std::process::Command;
    use std::time::{SystemTime, UNIX_EPOCH};

    #[test]
    fn emits_deterministic_module_sources() {
        let modules = emit_javascript_modules(&sample_program());

        assert_eq!(modules[0].path, "domain.mjs");
        assert_eq!(modules[1].path, "main.mjs");
        assert_eq!(
            modules[1].source,
            concat!(
                "// Generated by fx Phase 2.5 JavaScript emitter.\n",
                "// module main\n",
                "import * as __fx_import_domain from \"./domain.mjs\";\n",
                "\n",
                "export function __fx_user_main() { throw new Error(\"fx codegen for main.main is not implemented yet\"); }\n",
            )
        );
    }

    #[test]
    fn generated_names_do_not_collide_with_runtime_helpers() {
        assert_eq!(
            local_identifier(&CoreLocalName("__fx".to_string())),
            "__fx_user___fx"
        );
        assert_eq!(
            global_identifier(&CoreGlobalName {
                module: "main".to_string(),
                name: "match-variant".to_string(),
            }),
            "__fx_user_match_45_variant"
        );
    }

    #[test]
    fn emitted_cross_module_imports_execute_under_node() {
        let dir = std::env::temp_dir().join(format!(
            "fx-js-modules-{}",
            SystemTime::now()
                .duration_since(UNIX_EPOCH)
                .expect("system time")
                .as_nanos()
        ));
        fs::create_dir_all(&dir).expect("create temp dir");

        for module in emit_javascript_modules(&sample_program()) {
            let path = dir.join(module.path);
            if let Some(parent) = path.parent() {
                fs::create_dir_all(parent).expect("create module dir");
            }
            fs::write(path, module.source).expect("write module");
        }

        let output = Command::new("node")
            .arg("-e")
            .arg(format!(
                "import('{}/main.mjs').then((m) => console.log(typeof m.__fx_user_main))",
                dir.display()
            ))
            .output()
            .expect("node imports generated modules");

        let _ = fs::remove_dir_all(&dir);

        assert!(
            output.status.success(),
            "node failed\nstdout:\n{}\nstderr:\n{}",
            String::from_utf8_lossy(&output.stdout),
            String::from_utf8_lossy(&output.stderr)
        );
        assert_eq!(
            String::from_utf8(output.stdout)
                .expect("utf8 stdout")
                .trim(),
            "function"
        );
    }

    fn sample_program() -> CoreProgram {
        CoreProgram {
            modules: vec![
                CoreModule {
                    name: "domain".to_string(),
                    imports: Vec::new(),
                    declarations: vec![
                        CoreDecl::Type(CoreTypeDecl {
                            name: global("domain", "Person"),
                            export: true,
                            params: Vec::new(),
                            shape: CoreTypeShape::Record {
                                fields: vec![CoreTypeField {
                                    name: "name".to_string(),
                                    ty: Type::Text,
                                }],
                            },
                        }),
                        CoreDecl::Value(CoreValueDecl {
                            name: global("domain", "greet"),
                            export: true,
                            params: Vec::new(),
                            result_type: Type::Text,
                            body: text_expr(),
                        }),
                    ],
                },
                CoreModule {
                    name: "main".to_string(),
                    imports: vec![CoreImport {
                        module: "domain".to_string(),
                    }],
                    declarations: vec![CoreDecl::Value(CoreValueDecl {
                        name: global("main", "main"),
                        export: true,
                        params: Vec::new(),
                        result_type: Type::Text,
                        body: text_expr(),
                    })],
                },
            ],
        }
    }

    fn global(module: &str, name: &str) -> CoreGlobalName {
        CoreGlobalName {
            module: module.to_string(),
            name: name.to_string(),
        }
    }

    fn text_expr() -> CoreExpr {
        CoreExpr {
            ty: Type::Text,
            span: Span::point(0),
            tail: TailPosition::Tail,
            kind: CoreExprKind::Text("stub".to_string()),
        }
    }
}
